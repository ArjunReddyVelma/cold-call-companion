import React from 'react';
import { X, CheckCircle2, Bot } from 'lucide-react';
import { Call } from '../types/call';
import { OUTCOME_META, DEFAULT_STAGES } from '../constants/stages';

interface CallDetailModalProps {
  call: Call | null;
  onClose: () => void;
}

export const CallDetailModal: React.FC<CallDetailModalProps> = ({ call, onClose }) => {
  if (!call) return null;

  const outcomeMeta = call.final_outcome ? OUTCOME_META[call.final_outcome] : null;

  const formatDate = (isoString?: string | null) => {
    if (!isoString) return '—';
    try {
      const d = new Date(isoString);
      return d.toLocaleString('en-IN', {
        month: 'short',
        day: 'numeric',
        year: 'numeric',
        hour: '2-digit',
        minute: '2-digit'
      });
    } catch {
      return isoString;
    }
  };

  const getStageName = (num: number) => {
    const s = DEFAULT_STAGES.find((stg) => stg.stage_number === num);
    return s ? s.name : `Stage ${num}`;
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 backdrop-blur-sm p-4">
      <div className="bg-white border border-slate-200 rounded-xl max-w-2xl w-full shadow-2xl overflow-hidden animate-in fade-in zoom-in-95 duration-150 max-h-[90vh] flex flex-col">
        {/* Header */}
        <div className="bg-slate-900 text-white px-6 py-4 flex items-center justify-between border-b border-slate-800 shrink-0">
          <div>
            <div className="flex items-center gap-2">
              <h2 className="text-lg font-extrabold text-white">
                {call.prospect_name || 'Unknown Prospect'}
              </h2>
              {outcomeMeta && (
                <span
                  className="px-2.5 py-0.5 rounded text-[11px] font-bold border"
                  style={{
                    backgroundColor: outcomeMeta.bgColor,
                    color: outcomeMeta.color,
                    borderColor: outcomeMeta.borderColor
                  }}
                >
                  {outcomeMeta.label}
                </span>
              )}
            </div>
            <p className="text-xs text-slate-400 font-medium mt-0.5">
              {call.prospect_role ? `${call.prospect_role}, ` : ''}
              {call.company_name || 'Private Enterprise'}
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="text-slate-400 hover:text-white transition-colors"
            aria-label="Close"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6 space-y-6 overflow-y-auto">
          {/* Metadata Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 bg-slate-50 p-3.5 rounded-lg border border-slate-200 text-xs">
            <div>
              <span className="text-[10px] font-mono uppercase text-slate-400 block">Call Started</span>
              <span className="font-bold text-slate-800">{formatDate(call.started_at)}</span>
            </div>
            <div>
              <span className="text-[10px] font-mono uppercase text-slate-400 block">Call Ended</span>
              <span className="font-bold text-slate-800">{formatDate(call.ended_at)}</span>
            </div>
            <div>
              <span className="text-[10px] font-mono uppercase text-slate-400 block">Last Stage Reached</span>
              <span className="font-bold text-[#0029FF]">
                Stage {call.last_stage_reached}: {getStageName(call.last_stage_reached)}
              </span>
            </div>
            <div>
              <span className="text-[10px] font-mono uppercase text-slate-400 block">Next Step</span>
              <span className="font-bold text-slate-800 truncate block">
                {call.next_step || 'None recorded'}
              </span>
            </div>
          </div>

          {/* AI Summary Section */}
          <div className="bg-blue-50/60 border border-blue-200/80 rounded-xl p-4">
            <div className="flex items-center gap-2 mb-2">
              <Bot className="w-4 h-4 text-[#0029FF]" />
              <h4 className="text-xs font-bold font-mono uppercase tracking-wider text-[#0029FF]">
                AI-Generated Post-Call Summary
              </h4>
            </div>
            <p className="text-xs sm:text-sm text-slate-800 leading-relaxed">
              {call.summary || 'Summary unavailable or call not closed yet.'}
            </p>
            <p className="text-[10px] text-slate-400 font-mono mt-2">
              Generated by Gemini via backend only. AI never modifies user-selected outcomes or prospect notes.
            </p>
          </div>

          {/* Stage Visits History (Append-only log) */}
          <div>
            <h4 className="text-xs font-bold font-mono uppercase tracking-wider text-slate-500 mb-3 flex items-center justify-between">
              <span>Stage Visit History (Immutable Log)</span>
              <span className="text-[11px] text-slate-400 font-normal">
                {call.stage_results ? `${call.stage_results.length} visits recorded` : '0 visits'}
              </span>
            </h4>

            {call.stage_results && call.stage_results.length > 0 ? (
              <div className="space-y-2.5">
                {call.stage_results.map((sr, index) => (
                  <div
                    key={sr.id || index}
                    className="p-3.5 rounded-lg border border-slate-200 bg-white hover:border-slate-300 transition-colors shadow-xs"
                  >
                    <div className="flex items-center justify-between gap-2 mb-1.5">
                      <div className="flex items-center gap-2">
                        <span className="inline-flex items-center justify-center w-5 h-5 rounded-full bg-[#0029FF] text-white text-[10px] font-mono font-bold">
                          {sr.stage_number}
                        </span>
                        <span className="font-extrabold text-xs text-slate-900">
                          {getStageName(sr.stage_number)}
                        </span>
                        <span className="text-[10px] font-mono font-semibold px-2 py-0.5 rounded bg-slate-100 text-slate-600 border border-slate-200">
                          Visit {sr.visit_number}
                        </span>
                      </div>
                      <span className="text-[10px] font-mono text-slate-400">
                        {formatDate(sr.created_at)}
                      </span>
                    </div>

                    <div className="ml-7 space-y-1">
                      <div className="text-xs font-bold text-slate-800 flex items-center gap-1.5">
                        <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600 shrink-0" />
                        <span>Outcome: {sr.selected_result}</span>
                      </div>
                      {sr.prospect_words && (
                        <div className="text-xs text-slate-600 bg-slate-50 p-2 rounded border border-slate-200/60 italic">
                          <strong className="text-slate-700 not-italic">Prospect's words: </strong>
                          “{sr.prospect_words}”
                        </div>
                      )}
                    </div>
                  </div>
                ))}
              </div>
            ) : (
              <p className="text-xs text-slate-400 italic py-4 text-center bg-slate-50 rounded-lg">
                No stage visits were saved for this call.
              </p>
            )}
          </div>
        </div>

        {/* Footer */}
        <div className="px-6 py-3.5 bg-slate-50 border-t border-slate-200 flex justify-end shrink-0">
          <button
            type="button"
            onClick={onClose}
            className="px-4 py-2 text-xs font-bold text-slate-700 hover:bg-slate-200 rounded-md transition-colors"
          >
            Close Window
          </button>
        </div>
      </div>
    </div>
  );
};
